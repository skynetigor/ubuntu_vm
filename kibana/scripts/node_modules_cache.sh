#!/usr/bin/env bash
# Helpers for the per-commit node_modules cache used by bootstrap.sh.
#
# pnpm gives identical files (every empty file, for example) a single inode, and a cached copy made with
# `cp -al` adds one more hard link to each of them. ext4 allows 65000 links per inode, so a growing cache
# eventually fails with "Too many links". The helpers below never leave a half-built cache behind, copy
# the files that cannot be linked, and prune old caches.

# Usage: cache_node_modules <node_modules dir> <cache dir>. Returns 0 only when a complete cache exists.
cache_node_modules() {
  local source="$1" cache_dir="$2" partial="$2/node_modules.partial"
  mkdir -p "$cache_dir"
  rm -rf "$partial"
  # Link what can be linked, then copy whatever is still missing; the rename makes the cache appear whole.
  if { cp -al "$source" "$partial" 2>/dev/null || { mkdir -p "$partial" && cp -a --update=none "$source/." "$partial/"; }; } \
      && mv "$partial" "$cache_dir/node_modules"; then
    return 0
  fi
  rm -rf "$cache_dir"
  return 1
}

# Usage: prune_node_modules_caches <cache root> [max caches]. Keeps the newest caches and any cache that
# a checkout still links to.
prune_node_modules_caches() {
  local root="$1" max="${2:-24}" kept=0 dir in_use link
  [ -d "$root" ] || return 0
  in_use=$(for link in /opt/*/kibana/src/node_modules; do [ -L "$link" ] && readlink -f "$link"; done 2>/dev/null || true)
  for dir in $(ls -1dt "$root"/*/ 2>/dev/null); do
    dir="${dir%/}"
    kept=$((kept + 1))
    [ "$kept" -le "$max" ] && continue
    printf '%s\n' "$in_use" | grep -qF "$dir/" && continue
    echo "=== Pruning old node_modules cache $(basename "$dir") ==="
    rm -rf "$dir"
  done
  return 0
}
